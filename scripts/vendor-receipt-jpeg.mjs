#!/usr/bin/env node
// Keep the jpeg-js 0.4.4 entropy/IDCT implementation byte-for-byte; replace only
// its public RGB-output wrapper with a validation-only wrapper. No eval at runtime.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/jpeg-js/package.json'), 'utf8'));
if (pkg.version !== '0.4.4') throw new Error('Review the decoder before updating jpeg-js');
const source = fs.readFileSync(path.join(root, 'node_modules/jpeg-js/lib/decoder.js'), 'utf8');
const boundary = source.indexOf("if (typeof module !== 'undefined') {");
if (boundary < 0) throw new Error('Unexpected upstream decoder layout');
const wrapper = `
// Local modification: validation still entropy-decodes every scan and performs
// IDCT for every component via parse()/buildComponentData(). Upload validation
// never consumes RGB pixels: avoid public decode()'s two redundant full RGB
// buffers (6 bytes/pixel for RGB), retaining the SAME 64 MiB allocation budget.
// Structural container checks (SOF/SOS/EOI, byte/pixel limits) remain the caller's
// responsibility. This function is synchronous because jpeg-js's budget is global.
export default function validateReceiptJpeg(bytes) {
  const decoder = new JpegImage();
  decoder.opts = { tolerantDecoding: false, maxResolutionInMP: 16 };
  JpegImage.resetMaxMemoryUsage(64 * 1024 * 1024);
  decoder.parse(bytes);
  const count = decoder.components.length;
  // Preserve public decode()'s supported color modes; two-component PDF images
  // and four-component data without an Adobe marker were not supported either.
  if (![1, 3, 4].includes(count) || (count === 4 && !decoder.adobe))
    throw new Error('Unsupported color mode');
  for (const component of decoder.components) {
    const rows = Math.ceil(decoder.height * component.scaleY);
    const columns = Math.ceil(decoder.width * component.scaleX);
    if (!rows || !columns || component.lines.length < rows ||
        component.lines.some(line => line.length < columns))
      throw new Error('Incomplete decoded component');
  }
  return { width: decoder.width, height: decoder.height,
    allocatedBytes: JpegImage.getBytesAllocated() };
}
`;
const output = '// Generated by scripts/vendor-receipt-jpeg.mjs from jpeg-js 0.4.4.\n' + source.slice(0, boundary) + wrapper;
const target = path.join(root, 'functions/_vendor/receipt-jpeg-decoder.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Vendored decoder is out of sync');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  fs.copyFileSync(path.join(root, 'node_modules/jpeg-js/LICENSE'), path.join(root, 'functions/_vendor/jpeg-js-LICENSE'));
}
console.log('Receipt JPEG decoder: upstream entropy/IDCT unchanged, RGB output omitted');
