#!/usr/bin/env python3
"""Build lossless PDF PNG derivatives; never modify the supplied JPEG originals.

Only neutral light-paper alpha is removed. RGB values, dimensions, content,
ink colors and stamp details are preserved pixel-for-pixel from decoded JPEG.
"""
from pathlib import Path
from PIL import Image
import base64
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'site/pdf-assets'
exports = []
results = []
for stem, export in [('manager-signature', 'managerSignaturePng'), ('manager-stamp', 'managerStampPng')]:
    original = ASSETS / (stem + '.jpg')
    before = original.read_bytes()
    rgb = Image.open(original).convert('RGB')
    pixels = list(rgb.getdata())
    rgba = []
    for red, green, blue in pixels:
        low, high = min(red, green, blue), max(red, green, blue)
        if high - low > 15 or low <= 210:
            alpha = 255  # Never remove colored stamp ink or dark signature ink.
        elif low >= 238:
            alpha = 0
        else:
            alpha = round(255 * (238 - low) / 28)
        rgba.append((red, green, blue, alpha))
    out = Image.new('RGBA', rgb.size)
    out.putdata(rgba)
    destination = ASSETS / (stem + '.png')
    out.save(destination, optimize=True)
    decoded = Image.open(destination).convert('RGBA')
    assert decoded.size == rgb.size
    assert list(decoded.convert('RGB').getdata()) == pixels, 'RGB content changed'
    assert original.read_bytes() == before, 'Original JPEG changed'
    assert all(decoded.getpixel(point)[3] == 0 for point in [(0, 0), (rgb.width-1, 0), (0, rgb.height-1), (rgb.width-1, rgb.height-1)]), 'Paper corners must be transparent'
    data = destination.read_bytes()
    exports.append(f"export const {export} = Uint8Array.from(atob('{base64.b64encode(data).decode()}'), c => c.charCodeAt(0));\n")
    results.append({'asset': destination.name, 'dimensions': list(rgb.size), 'rgbUnchanged': True, 'originalSha256': hashlib.sha256(before).hexdigest(), 'pngSha256': hashlib.sha256(data).hexdigest(), 'transparentPixels': sum(pixel[3] == 0 for pixel in rgba), 'partialAlphaPixels': sum(0 < pixel[3] < 255 for pixel in rgba)})
(ROOT / 'functions/_lib/pdf-approval-assets.js').write_text('// Generated by scripts/build-pdf-approval-assets.py; source JPEGs remain unchanged.\n' + ''.join(exports))
print(json.dumps(results, indent=2))
